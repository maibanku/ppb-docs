  application_biz_key VARCHAR(64) COLLATE utf8mb4_bin NOT NULL COMMENT 'IAM应用业务键',
  client_subject VARCHAR(128) COLLATE utf8mb4_bin NOT NULL COMMENT '准入服务client主体，额外client映射通过IAM受控配置',
  application_status TINYINT NOT NULL DEFAULT 1 COMMENT '1启用 2停用',
