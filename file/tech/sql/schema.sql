  UNIQUE KEY uk_file_app_key (application_biz_key),
  CONSTRAINT ck_file_app_values CHECK (max_file_bytes > 0 AND default_quota_bytes >= 0 AND max_active_uploads > 0 AND upload_ttl_seconds > 0 AND access_ttl_seconds > 0 AND application_status IN (1,2))
